# ARITHMETIC OPERATIONS TEST
# ==========================================

a = 100
b = 25

# Addition
addition = a + b
print(addition)

# Subtraction
subtraction = a - b
print(subtraction)

# Multiplication
multiplication = a * b
print(multiplication)

# Integer division
division = a / b
print(division)

# Modulus
modulus = a % b
print(modulus)

# Complex expression
result = (a + b) * 2 - 50
print(result)
