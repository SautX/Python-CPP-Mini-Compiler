from compiler.backend import CompilerBackend


SOURCE = """
a = 20
b = 6

x = 10.5
y = 2.5

print(a + b)
print(x + y)
print(a + x)

print(a / b)
print(a // b)
print(a % b)
print(a ** 2)

print(a > b)
print(x < y)
print(a > 10 and x > 5)
print(a < 5 or x > 10)
print(not (a == b))

print(a & b)
print(a | b)
print(a ^ b)
print(a << 2)
print(a >> 1)
print(~a)

print(-x)
print(+a)
"""


def main():

    backend = CompilerBackend(
        compiler="g++"
    )

    try:
        print("\n1. COMPILING PYTHON SOURCE")

        program = backend.compile_source(
            SOURCE,
            optimize=True
        )

        print("Bytecode generation successful")

        print("\n2. GENERATED BYTECODE")

        backend.display_bytecode()

        print("\n3. GENERATING C++")

        cpp_file = backend.generate_cpp(
            "generated/generated.cpp"
        )

        print("Generated:", cpp_file)

        print("\n4. COMPILING C++")

        result = backend.compile_cpp(
            cpp_file,
            "output/executable.exe"
        )

        print("Executable:", result["executable"])

        print("\n5. RUNNING EXECUTABLE")

        output = backend.run_executable(
            result["executable"]
        )

        print(output["stdout"])

        if output["returncode"] != 0:
            print("Execution error:", output["stderr"])

    except Exception as error:
        print("\nCOMPILATION FAILED")
        print(error)


if __name__ == "__main__":
    main()
